/// Offline palette data. See docs/PALETTE_SOURCES.md for provenance.
///
/// Hardware palettes are numeric color-model renderings, not copied program
/// assets. Third-party palette permissions remain separate from the app license.
final class PalettePreset {
  const PalettePreset._({
    required this.id,
    required this.name,
    required this.description,
    required this.credit,
    required this.source,
    required this.license,
    required this.colors,
    this.colorNames = const [],
  });

  /// Personal palettes own snapshots; callers cannot mutate saved colors.
  factory PalettePreset.user({
    required String id,
    required String name,
    required List<int> colors,
    List<String> colorNames = const [],
  }) => PalettePreset._(
    id: id,
    name: name,
    description: 'Personal palette',
    credit: 'Your palette',
    source: '',
    license: 'Personal',
    colors: List<int>.unmodifiable(colors),
    colorNames: List<String>.unmodifiable(colorNames),
  );

  final String id;
  final String name;
  final String description;
  final String credit;
  final String source;
  final String license;

  /// Immutable ARGB values in the documented palette order.
  final List<int> colors;

  /// Optional labels, either empty or one label for each color.
  final List<String> colorNames;
}

