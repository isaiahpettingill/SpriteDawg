/// Offline palette data. See docs/PALETTE_SOURCES.md for provenance.
///
/// Hardware palettes are numeric color-model renderings, not copied program
/// assets. Third-party palette permissions remain separate from the app license.
final class PalettePreset {
  const PalettePreset._({
    required this.id,
    required this.name,
    required this.description,
    required this.credit,
    required this.source,
    required this.license,
    required this.colors,
  });

  final String id;
  final String name;
  final String description;
  final String credit;
  final String source;
  final String license;

  /// Immutable opaque ARGB values in the documented palette order.
  /// The engine handles document transparency separately when applying a preset.
  final List<int> colors;
}

