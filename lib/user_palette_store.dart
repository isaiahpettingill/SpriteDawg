import 'dart:convert';
import 'platform/palette_storage_io.dart'
    if (dart.library.js_interop) 'platform/palette_storage_web.dart';

import 'engine/palette_presets.dart';

/// User data lives outside documents and never mutates the built-in catalog.
/// All reads and mutations on an instance are serialized. A malformed library
/// is reported, not silently replaced with an empty one on the next save.
class UserPaletteStore {
  UserPaletteStore(this.resolveFile);

  static final shared = UserPaletteStore(paletteLibraryFile);

  final Future<File> Function() resolveFile;
  Future<void> _pending = Future<void>.value();
  int _sequence = 0;

  Future<T> _serialized<T>(Future<T> Function() action) {
    final result = _pending.then((_) => action());
    _pending = result.then<void>((_) {}, onError: (Object _, StackTrace _) {});
    return result;
  }

  Future<List<PalettePreset>> load() => _serialized(() async {
    final file = await resolveFile();
    return _read(file);
  });

  Future<PalettePreset> save({
    required String name,
    required List<int> colors,
    List<String> colorNames = const [],
    String? replaceId,
  }) {
    // Copy before entering the queue: later document edits cannot alter a save.
    final snapshot = List<int>.of(colors);
    final names = List<String>.of(colorNames);
    return _serialized(() async {
      final file = await resolveFile();
      final current = await _read(file);
      if (replaceId != null && !current.any((p) => p.id == replaceId)) {
        throw const FormatException('The personal palette no longer exists.');
      }
      if (replaceId == null && current.length >= 256) {
        throw const FormatException('The personal palette library is full.');
      }
      final trimmed = name.trim();
      if (trimmed.length > 80) {
        throw const FormatException('Use a palette name of 1–80 characters.');
      }
      _validate(trimmed, snapshot, names);
      var unique = trimmed;
      var suffix = 2;
      final used = current
          .where((p) => p.id != replaceId)
          .map((p) => p.name.toLowerCase())
          .toSet();
      while (used.contains(unique.toLowerCase())) {
        final ending = ' (${suffix++})';
        final length = trimmed.length < 80 - ending.length
            ? trimmed.length
            : 80 - ending.length;
        unique = '${trimmed.substring(0, length)}$ending';
      }
      // Collision suffixes are generated by us, not silently overwriting data.
      var id = '';
      do {
        id = 'user-${DateTime.now().microsecondsSinceEpoch}-${_sequence++}';
      } while (current.any((p) => p.id == id));
      final preset = PalettePreset.user(
        id: replaceId ?? id,
        name: unique,
        colors: snapshot,
        colorNames: names,
      );
      await _write(file, [
        for (final p in current)
          if (p.id == replaceId) preset else p,
        if (replaceId == null) preset,
      ]);
      return preset;
    });
  }

  Future<void> delete(String id) => _serialized(() async {
    if (!id.startsWith('user-')) {
      throw const FormatException('Built-in palettes cannot be deleted.');
    }
    final file = await resolveFile();
    final current = await _read(file);
    if (!current.any((p) => p.id == id)) return;
    await _write(file, current.where((p) => p.id != id).toList());
  });

  static void _validate(String name, List<int> colors, List<String> names) {
    if (name.isEmpty ||
        name.length > 80 ||
        name.contains(RegExp(r'[\x00-\x1f]'))) {
      throw const FormatException('Use a palette name of 1–80 characters.');
    }
    if (colors.isEmpty ||
        colors.length > 256 ||
        colors.any((c) => c < 0 || c > 0xffffffff)) {
      throw const FormatException('A palette must contain 1–256 ARGB colors.');
    }
    if ((names.isNotEmpty && names.length != colors.length) ||
        names.any((n) => utf8.encode(n).length > 65535)) {
      throw const FormatException('Palette swatch names are invalid.');
    }
  }

  Future<List<PalettePreset>> _read(File file) async {
    if (!await file.exists()) return const [];
    if (await file.length() > 4 * 1024 * 1024) {
      throw const FormatException('The palette library is too large.');
    }
    final decoded = jsonDecode(await file.readAsString());
    if (decoded is! Map ||
        decoded['version'] != 1 ||
        decoded['palettes'] is! List) {
      throw const FormatException('Unsupported or damaged palette library.');
    }
    final records = decoded['palettes'] as List;
    if (records.length > 256) {
      throw const FormatException('The palette library has too many entries.');
    }
    final result = <PalettePreset>[];
    final ids = <String>{};
    for (final record in records) {
      if (record is! Map ||
          record['id'] is! String ||
          !(record['id'] as String).startsWith('user-') ||
          record['name'] is! String ||
          record['colors'] is! List ||
          !(record['colors'] as List).every((c) => c is int) ||
          record['colorNames'] is! List ||
          !(record['colorNames'] as List).every((n) => n is String)) {
        throw const FormatException('A personal palette entry is damaged.');
      }
      final id = record['id'] as String;
      if (!ids.add(id)) {
        throw const FormatException('Duplicate palette identity.');
      }
      final name = record['name'] as String;
      final colors = (record['colors'] as List).cast<int>();
      final names = (record['colorNames'] as List).cast<String>();
      _validate(name, colors, names);
      result.add(
        PalettePreset.user(
          id: id,
          name: name,
          colors: colors,
          colorNames: names,
        ),
      );
    }
    return List.unmodifiable(result);
  }

  Future<void> _write(File file, List<PalettePreset> palettes) async {
    final bytes = utf8.encode(
      jsonEncode({
        'version': 1,
        'palettes': [
          for (final p in palettes)
            {
              'id': p.id,
              'name': p.name,
              'colors': p.colors,
              'colorNames': p.colorNames,
            },
        ],
      }),
    );
    if (bytes.length > 4 * 1024 * 1024) {
      throw const FormatException('The palette library would be too large.');
    }
    await file.parent.create(recursive: true);
    final temporary = File('${file.path}.tmp');
    try {
      await temporary.writeAsBytes(bytes, flush: true);
      // Android/Linux rename replaces the destination atomically. Never delete
      // the old file first; a failed write/rename must retain the old library.
      await temporary.rename(file.path);
    } finally {
      if (await temporary.exists()) await temporary.delete();
    }
  }
}
